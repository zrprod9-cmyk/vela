# gen_r4.py SR_R_COMP OUTDIR : writes OUTDIR/sr_r4.comp from sr_r.comp (the base reproject and rule kernel).
# The base kernel searches the 32 ring candidates around a pixel for every pixel on its own. This generator splits the work over a
# 2x2 cell: the 4 lanes of a cell (8x8 workgroup, lane = x + 8y) each fetch every 4th of the 32 candidates around the cell anchor
# (even x, even y) once, and test each fetched candidate against all 4 pixels' own references (dilated motion m0, own motion mr0,
# own depth d0, own target; shuffled in from the cell's lanes). The per-pixel bits (edge, uncovered) are OR-ed over the cell with
# subgroupShuffleXor 1 and 8, so every pixel sees all 32 candidates with its own reference (using the anchor's reference for all
# 4 pixels leaves specks along uncovered edges). The 33rd candidate q = p + D_p is per pixel.
# Cost: a candidate within SR_DIFF of every reference of the cell (triangle inequality around the anchor) or of the lane's last
# tested candidate is skipped; probes go through one call site (pending mask), depth is re-fetched in the probe (registers).
# Pixels whose own motion is within 0.5 px of the anchor's share one probe per candidate; a pixel with another motion (mixed cell
# at a motion edge) gets its own probe. The cell's other motions are kept as f16 offsets from the anchor's own motion (register count).
import sys
L2_BASE = '// SPDX-License-Identifier: GPL-2.0-or-later (frame-skip rules derived from fsr4-shader-performance-overrides, FSR 4.1.2 lossy); reproject and rule kernel (base of sr_r4.comp)'
L2_R4 = '// SPDX-License-Identifier: GPL-2.0-or-later (frame-skip rules derived from fsr4-shader-performance-overrides, FSR 4.1.2 lossy); 2x2-cell shared-fetch rule search with per-pixel references (generated by tools/gen_r4.py from src/sr_r.comp)'
O = sys.argv[2]
R = open(sys.argv[1]).read()
a = R.index('uint sr_cell(ivec2 ip, vec2 m0, ivec2 lim) {'); b = R.index('\n}\n', a) + 3
NEW = r'''bool sr_probe(ivec2 pp, vec2 mr0, vec2 mn_, ivec2 lim) {   // round-2 uncovered probe for pixel pp (own motion mr0) against neighbour motion mn_
    float d0 = texelFetch(r_depth, pp, 0).x; vec2 tgt = vec2(pp) + mr0; float eps = max(1e-4, 0.01 * abs(d0)); vec2 rf = tgt - mn_;
    for (int it = 0; it < 2; it++) {
        ivec2 r0 = ivec2(roundEven(rf)); bool found = false; vec2 mf = vec2(0.0);
        for (int j = 0; j < 9; j++) { ivec2 r = clamp(r0 + ivec2(j % 3 - 1, j / 3 - 1), ivec2(0), lim);
            vec2 mr = sr_mv(r); if (length(mr - mr0) < SR_DIFF) continue;
            float dr = texelFetch(r_depth, r, 0).x; found = true; mf = mr;
            if (length(vec2(r) + mr - tgt) <= 1.5 && dr < d0 - eps) return true; }
        if (!found) return false; rf = tgt - mf; }
    return false;
}
float h2(f16vec2 v) { vec2 w = vec2(v); return dot(w, w); }   // squared length in f32 (no f16 overflow)
const float SR_SAME = 0.25;   // (0.5 px)^2: same motion as the anchor -> share its probe
uint sr_cell(ivec2 ip, vec2 m0p, ivec2 lim) {
    uint al = gl_SubgroupInvocationID & ~9u; ivec2 ia = ip & ivec2(~1); int k4 = (ip.x & 1) + 2 * (ip.y & 1);
    vec2 mr0p = sr_mv(ip);
    vec2 A0 = subgroupShuffle(m0p, al), A1 = subgroupShuffle(m0p, al + 1u), A2 = subgroupShuffle(m0p, al + 8u), A3 = subgroupShuffle(m0p, al + 9u);   // dilated motions
    vec2 B0 = subgroupShuffle(mr0p, al), B1 = subgroupShuffle(mr0p, al + 1u), B2 = subgroupShuffle(mr0p, al + 8u), B3 = subgroupShuffle(mr0p, al + 9u); // own motions
    f16vec2 a1 = f16vec2(A0 - B0), a2 = f16vec2(A1 - B0), a3 = f16vec2(A2 - B0), a4 = f16vec2(A3 - B0), b1 = f16vec2(B1 - B0), b2 = f16vec2(B2 - B0), b3 = f16vec2(B3 - B0);   // cell offsets from the anchor's motion, f16 (registers)
    float rad2 = max(max(max(h2(a1), h2(a2)), max(h2(a3), h2(a4))), max(max(h2(b1), h2(b2)), h2(b3)));
    float qr = max(SR_DIFF - sqrt(rad2), 0.0); qr *= qr;   // cell radius around the anchor's own motion
    uint g0 = 1u | (h2(b1) < SR_SAME ? 2u : 0u) | (h2(b2) < SR_SAME ? 4u : 0u) | (h2(b3) < SR_SAME ? 8u : 0u);   // pixels moving with the anchor
    const ivec2 DI[8] = ivec2[8](ivec2(1, 0), ivec2(-1, 0), ivec2(0, 1), ivec2(0, -1), ivec2(1, 1), ivec2(-1, -1), ivec2(1, -1), ivec2(-1, 1));
    const int RR[4] = int[4](3, 8, 16, 24);
    bool nou = (pc.flags & 16u) != 0u; uint bits = 0u; vec2 last = vec2(1e9); const float D2 = SR_DIFF * SR_DIFF;   // bit c: edge of pixel c, bit 4 + c: uncovered
    for (int i = k4; i < 32; i += 4) {   // this lane's quarter of 8 directions x 3, 8, 16, 24 cells (diagonals x0.7) around the anchor, tested for all 4 pixels
        int k = i & 7, rr = RR[i >> 3]; ivec2 dv = k < 4 ? DI[k] * rr : DI[k] * ((rr * 7 + 5) / 10);
        vec2 mn_ = sr_mv(clamp(ia + dv, ivec2(0), lim));
        vec2 e0 = mn_ - B0, el = mn_ - last; if (dot(e0, e0) < qr || dot(el, el) < 0.25) continue;   // same motion as every pixel of the cell, or as the last one tested
        last = mn_;
        f16vec2 eh = f16vec2(clamp(e0, vec2(-4096.0), vec2(4096.0)));
        if (i < 24) bits |= (h2(eh - a1) >= D2 ? 1u : 0u) | (h2(eh - a2) >= D2 ? 2u : 0u) | (h2(eh - a3) >= D2 ? 4u : 0u) | (h2(eh - a4) >= D2 ? 8u : 0u);
        if (nou) continue;
        uint pend = ((dot(e0, e0) >= D2 ? 1u : 0u) | (h2(eh - b1) >= D2 ? 2u : 0u) | (h2(eh - b2) >= D2 ? 4u : 0u) | (h2(eh - b3) >= D2 ? 8u : 0u)) & ~(bits >> 4);
        uint pg = pend & g0;   // pixels with the anchor's motion share one probe (lowest pending one's reference); others probe alone
        if (pg != 0u) pend = (pend & ~g0) | (1u << findLSB(pg));
        while (pend != 0u) { int c = findLSB(pend); pend &= pend - 1u;
            vec2 mrc = B0 + vec2(c == 0 ? f16vec2(0.0) : (c == 1 ? b1 : (c == 2 ? b2 : b3)));
            if (sr_probe(ia + ivec2(c & 1, c >> 1), mrc, mn_, lim)) bits |= (((g0 >> c) & 1u) != 0u ? g0 : (1u << c)) << 4; } }
    bits |= subgroupShuffleXor(bits, 1u); bits |= subgroupShuffleXor(bits, 8u);
    bool diff = ((bits >> k4) & 1u) != 0u, unc = ((bits >> (4 + k4)) & 1u) != 0u;
    ivec2 q0 = ivec2(roundEven(vec2(ip) + m0p)); bool outq = any(lessThan(q0, ivec2(0))) || any(greaterThan(q0, lim)); ivec2 qc = clamp(q0, ivec2(0), lim);
    { vec2 mn_ = sr_mv(qc);   // candidate 33: q = p + D_p, per pixel as round 2
      if (length(mn_ - m0p) >= SR_DIFF) diff = true;
      if (!unc && !nou && length(mn_ - mr0p) >= SR_DIFF) unc = sr_probe(ip, mr0p, mn_, lim); }
    bool rest = all(lessThan(abs(m0p), vec2(0.25))) && !diff && (pc.flags & 32u) == 0u;
    return (rest ? 1u : 0u) | ((unc || (outq && !rest)) ? 4u : 0u) | (diff ? 8u : 0u);
}
'''
R = R[:a] + NEW + R[b:]
ext = '#extension GL_KHR_shader_subgroup_basic : require\n#extension GL_KHR_shader_subgroup_shuffle : require\n'
R = R.replace('#extension GL_EXT_samplerless_texture_functions : require\n', '#extension GL_EXT_samplerless_texture_functions : require\n' + ext, 1)
R = R.replace(L2_BASE, L2_R4, 1)
assert 'subgroupShuffleXor' in R and R.count('uint sr_cell(') == 1
open(O + '/sr_r4.comp', 'w').write(R); print('ok')
