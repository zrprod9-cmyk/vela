"""Write the generated SPIR-V headers of the provider overlay from compiled .spv files.

usage: gen_hpp.py fv <out.hpp> fv_xfer.spv fv_select.spv
       gen_hpp.py npu <out.hpp> npu_pack.spv npu_unpack.spv ...
"""
import struct
import sys


def words(path):
    b = open(path, "rb").read()
    return struct.unpack("<%dI" % (len(b) // 4), b)


kind, out_path, spvs = sys.argv[1], sys.argv[2], sys.argv[3:]
if kind == "fv":
    o = ["// generated by spirv-sources/build.sh from fv/fv_xfer.comp, fv/fv_select.comp (glslangValidator -V --target-env vulkan1.2)",
         "#pragma once", "#include <cstdint>", "namespace fv {"]
    for path, name in zip(spvs, ("kXferSpv", "kSelectSpv")):
        o.append("inline constexpr uint32_t %s[] = {%s};" % (name, ",".join("0x%08x" % x for x in words(path))))
    o.append("}")
elif kind == "npu":
    o = ["#pragma once", "// generated by spirv-sources/build.sh from npu/npu_*.comp (glslangValidator -V --target-env vulkan1.1)",
         "#include <cstdint>", "namespace fsr4npu_spv {"]
    for path in spvs:
        name = path.split("/")[-1].split(".")[0]
        o.append("inline constexpr std::uint32_t k_%s[] = {%s};" % (name, ",".join("0x%08x" % x for x in words(path))))
    o.append("}")
else:
    raise SystemExit("unknown kind " + kind)
open(out_path, "w", newline="\n").write("\n".join(o) + "\n")
