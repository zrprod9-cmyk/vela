"""Small helper shaders of -> src/misc_spv.h (uint32 arrays).

    python -I tools/gen_misc_spv.py --glslang <glslangValidator>
"""
import argparse
import os
import struct
import subprocess
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SHADERS = [("misc_spv_exposure_div_comp", "exposure_div.comp"), ("misc_spv_hdr_wrap_comp", "hdr_wrap.comp")]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--glslang", required=True)
    a = ap.parse_args()
    out = ["#pragma once", "// Generated by tools/gen_misc_spv.py from shaders/. Do not edit.", "#include <cstdint>", ""]
    with tempfile.TemporaryDirectory() as tmp:
        for name, src in SHADERS:
            spv = os.path.join(tmp, name + ".spv")
            subprocess.run([a.glslang, "-V", "--target-env", "vulkan1.1", os.path.join(ROOT, "shaders", src), "-o", spv],
                           check=True, capture_output=True)
            data = open(spv, "rb").read()
            words = struct.unpack("<%dI" % (len(data) // 4), data)
            body = ",".join(("\n    " if i % 8 == 0 else " ") + "0x%08x" % w for i, w in enumerate(words))
            out.append("inline const uint32_t %s[] = {%s\n};" % (name, body))
    open(os.path.join(ROOT, "src", "misc_spv.h"), "w", newline="\n").write("\n".join(out) + "\n")
    print("wrote src/misc_spv.h")


if __name__ == "__main__":
    main()
