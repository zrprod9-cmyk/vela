"""SGSR 2 (Qualcomm, BSD-3-Clause; shaders/SGSR2_LICENSE) compute passes -> src/sgsr2_spv.h (uint32 arrays).

Compile first (glslang of the spvtools:3 image), then write the header:
    docker run --rm -v <this>/shaders:/s:ro -v <spv dir>:/o spvtools:3 sh -c \
      'for p in convert upscale; do glslangValidator -V --target-env vulkan1.1 /s/sgsr2_$p.comp -o /o/sgsr2_$p.spv; done'
    python -I tools/gen_sgsr2_spv.py --spv <spv dir>
"""
import argparse
import os
import struct

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--spv", required=True)
    a = ap.parse_args()
    out = ["#pragma once",
           "// Generated by tools/gen_sgsr2_spv.py from shaders/sgsr2_{convert,upscale}.comp. Do not edit.",
           "// Snapdragon(TM) Game Super Resolution 2: Copyright (c) 2023-2024, Qualcomm Innovation Center, Inc.",
           "// All rights reserved. SPDX-License-Identifier: BSD-3-Clause (full text: shaders/SGSR2_LICENSE).",
           "#include <cstdint>", ""]
    for p in ("convert", "upscale"):
        data = open(os.path.join(a.spv, "sgsr2_%s.spv" % p), "rb").read()
        words = struct.unpack("<%dI" % (len(data) // 4), data)
        assert words[0] == 0x07230203, "not SPIR-V"
        body = ",".join(("\n    " if i % 8 == 0 else " ") + "0x%08x" % w for i, w in enumerate(words))
        out.append("inline const uint32_t sgsr2_%s_spv[] = {%s\n};" % (p, body))
    open(os.path.join(ROOT, "src", "sgsr2_spv.h"), "w", newline="\n").write("\n".join(out) + "\n")
    print("wrote src/sgsr2_spv.h")


if __name__ == "__main__":
    main()
